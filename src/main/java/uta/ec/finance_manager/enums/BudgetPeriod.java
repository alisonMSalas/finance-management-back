package uta.ec.finance_manager.enums;

/**
 * Enumeración de los períodos de tiempo para los presupuestos.
 * <p>
 * Define los diferentes períodos en los que un usuario puede
 * establecer límites de gasto en su presupuesto.
 * </p>
 * 
 * @author Finance Manager Team
 * @version 1.0
 * @since 2024
 */
public enum BudgetPeriod {
    /** Presupuesto con período de una semana */
    SEMANAL,
    
    /** Presupuesto con período de un mes */
    MENSUAL,
    
    /** Presupuesto con período de un año */
    ANUAL
}
